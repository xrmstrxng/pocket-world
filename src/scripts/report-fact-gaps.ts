import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { manualFacts } from "../content/country-facts/manual-facts";
import type { Country } from "../entities/country/country.types";
import { indicatorKeys, type CountryFactsSnapshot } from "../entities/country-facts/country-facts.types";
import { listFactGaps, mergeManualFacts, type FactGap } from "../entities/country-facts/country-facts.utils";
import { FULL_TIER_EXTRA_ALPHA3_CODES, UN_MEMBER_ALPHA3_CODES } from "../shared/constants/un-member-codes";

const GAP_LABELS: Record<FactGap, string> = {
  gdpUsd: "GDP",
  gdpPerCapitaUsd: "GDP per capita",
  lifeExpectancyYears: "Life expectancy",
  urbanPopulationPercent: "Urban population",
  internetUsersPercent: "Internet users",
  forestAreaPercent: "Forest area",
  co2PerCapitaTonnes: "CO₂ per capita",
  highestPoint: "Highest point",
  highestPointNamePtBr: "Highest point name (pt-BR)",
};

async function main() {
  const root = process.cwd();
  const countries = JSON.parse(await readFile(resolve(root, "src/data/generated/countries.json"), "utf8")) as Country[];
  const facts = JSON.parse(await readFile(resolve(root, "src/data/generated/country-facts.json"), "utf8")) as CountryFactsSnapshot;
  const { snapshot, redundant } = mergeManualFacts(facts, manualFacts);
  const factsByAlpha3 = new Map(snapshot.countries.map((country) => [country.alpha3, country]));

  const isFullTier = (alpha3: string) => UN_MEMBER_ALPHA3_CODES.has(alpha3) || FULL_TIER_EXTRA_ALPHA3_CODES.has(alpha3);
  const rows = countries
    .map((country) => {
      const record = factsByAlpha3.get(country.codes.alpha3);
      return { country, gaps: record ? listFactGaps(record) : ([...indicatorKeys, "highestPoint"] as FactGap[]) };
    })
    .filter((row) => row.gaps.length)
    .sort((a, b) => a.country.names.common.en.localeCompare(b.country.names.common.en));

  const table = (subset: typeof rows) => [
    "| Country | Alpha-3 | Missing |",
    "| --- | --- | --- |",
    ...subset.map(({ country, gaps }) => `| ${country.names.common.en} (${country.names.common["pt-BR"]}) | \`${country.codes.alpha3}\` | ${gaps.map((gap) => GAP_LABELS[gap]).join(", ")} |`),
  ].join("\n");

  const counts = (Object.keys(GAP_LABELS) as FactGap[]).map((gap) => {
    const affected = rows.filter((row) => row.gaps.includes(gap));
    return `| ${GAP_LABELS[gap]} | ${affected.filter((row) => isFullTier(row.country.codes.alpha3)).length} | ${affected.filter((row) => !isFullTier(row.country.codes.alpha3)).length} |`;
  });

  const fullTier = rows.filter((row) => isFullTier(row.country.codes.alpha3));
  const territories = rows.filter((row) => !isFullTier(row.country.codes.alpha3));

  const markdown = `# Country facts: data gaps

> Generated by \`pnpm facts:gaps\` from \`country-facts.json\` (synced ${facts.generatedAt}) and \`src/content/country-facts/manual-facts.ts\`. Do not edit by hand.

To fill a gap, add a value with its year and source to \`src/content/country-facts/manual-facts.ts\`, then run \`pnpm facts:gaps\` again.

## Summary

| Field | Full-tier countries missing it | Territories missing it |
| --- | --- | --- |
${counts.join("\n")}

${redundant.length ? `## Redundant manual entries\n\nThe open-data snapshot now provides these values, so the manual entries are ignored and can be removed:\n\n${redundant.map((item) => `- \`${item}\``).join("\n")}\n\n` : ""}## Full tier: UN members, Vatican City, Palestine, Taiwan and Kosovo (${fullTier.length})

${fullTier.length ? table(fullTier) : "No gaps."}

## Other territories (${territories.length})

${territories.length ? table(territories) : "No gaps."}
`;

  const outputPath = resolve(root, "docs/data-gaps.md");
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, markdown, "utf8");
  console.log(`Gaps: ${fullTier.length} full-tier countries and ${territories.length} territories with missing fields`);
  if (redundant.length) console.log(`Redundant manual entries: ${redundant.join(", ")}`);
  console.log(`Output: ${outputPath}`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
